"""Rule amf-drc-output-route: AMF's 2023 DRC sheet pastes its total value after leverage and funging as a number
(AMF!B217), and its bottom line divides by the computed total before leverage to get the leverage adjustment, so in
our view every slider's move was cancelled (the side-effects weight, the value of a child's life, the discount
rate: the headline stayed put). The pasted total becomes the computed total times GiveWell's leverage/funging
ratio (the sheet's two totals, B217 / the total after supplemental adjustments), so the sheet still reproduces and
the sliders reach the result through the rows they move.

    python3 scripts/_amf-drc-output-route.py
"""
import json
from pathlib import Path

p = Path(__file__).resolve().parent.parent / "models/grants/givewell/against-malaria-foundation-2023-amf-drc.json"
text = p.read_text()
m = json.loads(text)
assert json.dumps(m, indent=2, ensure_ascii=False) + "\n" == text
rows = m["rows"]
by = {r["id"]: r for r in rows}
leaf = by["total_units_of_value_generated_by_philanthropic_spending_aft"]
if "value" in leaf:
    pasted = leaf.pop("value")
    leaf.pop("kind", None)
    total = by["total_units_of_value_generated_2"]["expected"]
    ratio = {
        "id": "leverage_funging_ratio_of_total_value",
        "label": "Units of value after leverage and funging, per unit of value generated by all spending",
        "section": leaf.get("section"),
        "value": pasted / total,
        "kind": "estimate",
        "source": leaf.get("source"),
        "format": "number",
        "explainer": (f"GiveWell's sheet pastes the value after leverage and funging as a number ({pasted:,.0f} units of value, AMF!B217) "
                      f"beside the computed total before them ({total:,.0f}); this is their ratio. Read as a ratio, the sheet's "
                      "leverage and funging scale with the value the rows above compute, so the sliders that move that value "
                      "(side effects, the value of a child's life, the discount rate) move the result instead of being "
                      "cancelled by the pasted figure."),
    }
    leaf["formula"] = "total_units_of_value_generated_2 * leverage_funging_ratio_of_total_value"
    leaf["expected"] = pasted
    leaf["explainer"] = ("The sheet's pasted total (AMF!B217) as the computed total times the sheet's leverage/funging ratio, so it "
                         "moves with the rows above it; at the sheet's values it is the sheet's figure.")
    rows.insert(rows.index(leaf), ratio)
p.write_text(json.dumps(m, indent=2, ensure_ascii=False) + "\n")
print("amf-drc: total after leverage/funging = computed total x the sheet's ratio")
