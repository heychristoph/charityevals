// Writes a write-up for every charity whose main model is a bulk import and that has none yet.
//   npx tsx scripts/bulk-writeups.ts
// The write-up is built from the data: what each evaluator published, each model's result and date,
// and how faithfully the import reproduces it. It starts with a marker comment; replace the whole file
// with a hand-written evaluation when there is one (the script never overwrites a file without it).
import { existsSync, readFileSync, readdirSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MOVED_MONEY_ROWS, SUCCESS_FACT, sameFormula } from "../src/engine/moved-money";
import { buildLibrary, assumptionValues, comparable, headline, modelsOf, type ResolvedModel } from "../src/engine/model";
import { primaryModel } from "../src/engine/ranking";
import { formatYears, plainModelName } from "../src/lib/format";

const MARK = "<!-- generated by scripts/bulk-writeups.ts: replace with a hand-written evaluation -->";
const root = join(import.meta.dirname, "..");
const read = (p: string) => JSON.parse(readFileSync(p, "utf8"));
const walk = (d: string): string[] => readdirSync(d).flatMap((f) => {
  const p = join(d, f);
  return statSync(p).isDirectory() ? walk(p) : f.endsWith(".json") ? [p] : [];
});
const lib = buildLibrary(walk(join(root, "models")).map(read), read(join(root, "assumptions/default.json")), walk(join(root, "facts")).map(read),
  walk(join(root, "charities")).map(read), read(join(root, "owners.json")));
const av = assumptionValues(lib.assumptions);

const month = (d?: string) => (d ? new Date(d).toLocaleDateString("en-GB", { year: "numeric", month: "long", timeZone: "UTC" }) : "undated");
// Rounded as the site rounds it.
const fmt = formatYears;
// The site's own number: the headline the model page shows (engine headline(), default values), in
// years of healthy life per $1,000. The span lets the page keep it in step with the reader's values
// (src/components/Headline.tsx); the text inside is the default. A unit with no exchange rate stays in
// its own terms.
const result = (m: ResolvedModel) => {
  const v = headline(lib, m, av);
  if (!comparable(lib, m)) return `${fmt(v)} ${lib.assumptions.units[m.output!.unit].label} per dollar`;
  return `<span data-figure="headline" data-model="${m.id}">${fmt(v)}</span> years of healthy life per $1,000`;
};
const fidelity = (m: ResolvedModel) => {
  const reproduced = m.rows.filter((r) => r.expected !== undefined).length;
  const fixed = m.rows.filter((r) => r.explainer?.startsWith("Calculated in the source sheet")).length;
  return { reproduced, fixed };
};
const url = (m: ResolvedModel) => (primaryModel(lib, m.charity)?.id === m.id ? `/${m.charity}` : `/${m.charity}/${m.id}`);

/** A meta charity's model values the money it moves by the site's shared method (docs/normalization.md
 * 2.8): what that changes from the evaluator's own valuation, in a sentence or two. */
function movedMoney(m: ResolvedModel, name: string): string | undefined {
  const v = m.byId.get("moved_dollar_value");
  if (!v) return undefined;
  const owner = lib.owners.get(m.owner)!.name;
  const mix = sameFormula(v.formula, MOVED_MONEY_ROWS.moved_dollar_value.formula);
  const where = mix
    ? "where effective donors give (Giving What We Can's split: about 60% global health, 10% animals, 10% longtermist causes, which the site doesn't value), each at its live result on this site"
    : "GiveWell's Top Charities, each at its live result on this site";
  const net = m.byId.has("moved_dollar_net_value") ? " Half the money is counted as new; the rest only for the gain over GiveDirectly." : "";
  const success = m.rows.some((r) => r.factDeps.includes(SUCCESS_FACT)) ? " A new organisation's chance of success is the site's shared 56%." : "";
  return `**Where we differ from ${owner}.** ${name} works through the money it moves or redirects, not a programme of its own, so our view values each such dollar the way the site values every meta charity's: by ${where}, so the sliders move it too.${net}${success} ${owner}'s own valuation stays in the evaluator view. [How money moved is valued](https://github.com/heychristoph/charityevals/blob/main/docs/normalization.md#28-money-moved-success-and-career-changes-one-method-october-2026).`;
}

let written = 0;
for (const c of lib.charities.values()) {
  const models = modelsOf(lib, c.id);
  // The write-up sits on the charity's main page, which shows the model the rankings use.
  const main = primaryModel(lib, c.id);
  if (!main?.bulk) continue;
  const generated = (f: string) => existsSync(f) && readFileSync(f, "utf8").startsWith(MARK);
  // A hand-written evaluation filed under the charity's first model keeps its place on the main page.
  const first = join(root, "writeups", `${models[0].id}.md`);
  if (models[0].id !== main.id && existsSync(first) && !generated(first)) continue;
  const file = join(root, "writeups", `${main.id}.md`);
  if (existsSync(file) && !generated(file)) continue;
  // A generated write-up left under a model that is no longer the main one would repeat stale prose.
  if (models[0].id !== main.id && generated(first)) unlinkSync(first);
  const owners = [...new Set(models.map((m) => lib.owners.get(m.owner)!.name))];
  const sheets = models.filter((m) => !m.source?.sheet?.includes("guesstimate"));
  const guess = models.filter((m) => m.source?.sheet?.includes("guesstimate"));
  const lines = [
    MARK,
    `${c.summary ?? c.name} ${owners.length > 2 ? `${owners.slice(0, -1).join(", ")} and ${owners.at(-1)}` : owners.join(" and ")} ${models.length === 1 ? "published one public model" : `published ${models.length} public models`} of its work; ` +
      `the most recent, from ${month(main.source?.published)}, puts it at **${result(main)}**.`,
    "",
    "| Model | By | Date | Years of healthy life per $1,000 | Cells reproduced |",
    "| --- | --- | --- | --- | --- |",
    ...models.map((m) => {
      const f = fidelity(m);
      return `| [${plainModelName(m.name).replace(/\|/g, "/")}](${url(m)}) | ${lib.owners.get(m.owner)!.short} | ${month(m.source?.published)} | ${comparable(lib, m) ? `<span data-figure="headline" data-model="${m.id}">${fmt(headline(lib, m, av))}</span>` : result(m)} | ${f.reproduced}${f.fixed ? `, ${f.fixed} kept fixed` : ""} |`;
    }),
    "",
    ...(main.theoretical
      ? [`**Purely theoretical.** ${lib.owners.get(main.owner)!.name}'s estimate is of the idea, written before ${c.name} existed, not of the charity's own results. ` +
        `It is shown because ${c.name} runs the programme today ([checked ${month(main.theoretical.checked)}](${main.theoretical.url})) and no model of its actual work exists yet.`, ""]
      : []),
    ...(movedMoney(main, c.name) ? [movedMoney(main, c.name)!, ""] : []),
    `We haven't written our own evaluation of this charity yet. [How imported models work](/method#imported-models).`,
    "",
  ];
  writeFileSync(file, lines.join("\n"));
  written++;
}
console.log(`${written} write-ups written`);
